# Sourced by docker-entrypoint.sh, which passes the real paths. The tests pass
# temporary ones. Never read a path from the environment here: root empties the
# runtime folder, so a path an operator can set is a path root can delete.

fail() {
  echo "stackyard: $*" >&2
  exit 1
}

# Write a file to find out. test -w reads the mode bits only, and reports a
# read-only filesystem as writable.
can_write() {
  probe="$(mktemp "$1/.writable.XXXXXX" 2>/dev/null)" || return 1
  rm -f "$probe"
}

# Usage: stackyard_main RUNTIME_DIR DATA_DIR ICONS_DIR INET6_PROC PORT_FLOOR_PROC -- COMMAND...
stackyard_main() {
  RUNTIME_DIR="$1"
  DATA_DIR="$2"
  ICONS_DIR="$3"
  INET6_PROC="$4"
  PORT_FLOOR_PROC="$5"
  [ "$6" = -- ] || fail "stackyard_main: expected -- before the command"
  shift 6

  REALIP_CONF="$RUNTIME_DIR/realip.conf"
  LISTEN_CONF="$RUNTIME_DIR/listen.conf"
  NGINX_USER_CONF="$RUNTIME_DIR/nginx-user.conf"
  SUPERVISOR_USER_CONF="$RUNTIME_DIR/supervisord-user.conf"
  MARKER="$RUNTIME_DIR/fatal"
  NGINX_TEMP_DIR="$RUNTIME_DIR/nginx"
  LISTEN_PORT="${LISTEN_PORT:-80}"
  uid="$(id -u)"

  case "$LISTEN_PORT" in
    '' | *[!0-9]* | 0*) fail "LISTEN_PORT must be a number from 1 to 65535, not \"$LISTEN_PORT\"" ;;
  esac
  [ "${#LISTEN_PORT}" -le 5 ] && [ "$LISTEN_PORT" -le 65535 ] ||
    fail "LISTEN_PORT must be a number from 1 to 65535, not \"$LISTEN_PORT\""
  [ "$LISTEN_PORT" != 3000 ] || fail "LISTEN_PORT cannot be 3000; the API uses that port inside the container"

  if [ "$uid" != 0 ]; then
    # Kernels before 4.11 have no such file and reserve every port below 1024.
    floor=1024
    if value="$(cat "$PORT_FLOOR_PROC" 2>/dev/null)"; then
      case "$value" in
        '' | *[!0-9]*) ;;
        *) floor="$value" ;;
      esac
    fi
    if [ "$LISTEN_PORT" -lt "$floor" ]; then
      fail "UID $uid cannot listen on port $LISTEN_PORT here; this system allows ports from $floor up for accounts other than root. Set LISTEN_PORT to $floor or higher and map that port, or start the container as root."
    fi
  fi

  if [ "$uid" = 0 ]; then
    # The API's account must not be able to plant a file or link here: root
    # writes into this folder next.
    mkdir -p "$RUNTIME_DIR"
    chown root:root "$RUNTIME_DIR"
    chmod 0755 "$RUNTIME_DIR"
    find "$RUNTIME_DIR" -mindepth 1 -delete
    # Create the temp folders as nginx. A chown needs CAP_CHOWN, which a root
    # start may not have, and nginx -t stops the container without it.
    mkdir -m 0777 "$NGINX_TEMP_DIR"
    su -s /bin/sh nginx -c "cd \"$NGINX_TEMP_DIR\" && mkdir -m 0700 client_body proxy fastcgi uwsgi scgi"
    chmod 0755 "$NGINX_TEMP_DIR"
  else
    { mkdir -p "$RUNTIME_DIR" 2>/dev/null && can_write "$RUNTIME_DIR"; } ||
      fail "UID $uid cannot write $RUNTIME_DIR. If the container's root filesystem is read-only, mount a tmpfs on $RUNTIME_DIR."
    mkdir -p "$NGINX_TEMP_DIR"
  fi

  {
    echo "# Generated by docker-entrypoint.sh. Do not edit."
    if [ "$uid" = 0 ]; then
      echo "user nginx;"
    fi
  } > "$NGINX_USER_CONF" || fail "cannot write $NGINX_USER_CONF"

  {
    echo "; Generated by docker-entrypoint.sh. Do not edit."
    if [ "$uid" = 0 ]; then
      printf '[supervisord]\nuser=root\n\n[program:api]\nuser=node\n'
    fi
  } > "$SUPERVISOR_USER_CONF" || fail "cannot write $SUPERVISOR_USER_CONF"

  # Stackyard runs its own nginx inside the container, so when it sits behind
  # another reverse proxy (Nginx Proxy Manager, Caddy, Traefik) the inner nginx
  # sees that proxy as the client. Every request then looks like it came from
  # one address, and per-client rate limiting degrades to one shared bucket.
  #
  # TRUSTED_PROXY names where the front proxy is. nginx then takes the real
  # client address from the forwarding headers those proxies already send by
  # default, so nothing has to be configured on their side and nothing
  # downstream has to parse a header chain.
  #
  #   TRUSTED_PROXY=172.18.0.0/16
  #   TRUSTED_PROXY="172.18.0.0/16 10.0.0.5"
  #
  # Unset means trust nothing, which is correct for direct access.
  {
    echo "# Generated by docker-entrypoint.sh from TRUSTED_PROXY. Do not edit."
    if [ -n "${TRUSTED_PROXY:-}" ]; then
      for cidr in $(echo "$TRUSTED_PROXY" | tr ',' ' '); do
        echo "set_real_ip_from $cidr;"
      done
      echo "real_ip_header X-Forwarded-For;"
      # Walk the chain from the right, skipping addresses we trust, so the real
      # client is found even with several proxies in front.
      echo "real_ip_recursive on;"
    else
      echo "# TRUSTED_PROXY not set: forwarding headers are not trusted."
    fi
  } > "$REALIP_CONF" || fail "cannot write $REALIP_CONF"

  # Some platforms reach the container only over IPv6, and nginx binds the IPv4
  # listener alone. Do not make this unconditional. nginx does not start when
  # it cannot bind, and a container without IPv6 then serves nothing.
  #
  # Not under /etc/nginx/http.d/ and not named .conf there. Alpine's nginx.conf
  # includes that glob at the http level, where `listen` is rejected.
  {
    echo "# Generated by docker-entrypoint.sh. Do not edit."
    echo "listen $LISTEN_PORT;"
    # Read it. Every file under /proc reports a size of 0, so -s is always false
    # here and would report IPv6 as absent on a container that has it.
    if [ -n "$(cat "$INET6_PROC" 2>/dev/null)" ]; then
      # ipv6only stays at nginx's default: this is a second listener beside the
      # IPv4 one, not a replacement for it.
      echo "listen [::]:$LISTEN_PORT;"
    else
      echo "# No IPv6 in this container: IPv4 only."
    fi
  } > "$LISTEN_CONF" || fail "cannot write $LISTEN_CONF"

  # A mounted volume carries the host's ownership. Started as root, the API runs
  # as node and cannot write a root-owned mount: every config and icon write
  # then fails. Started as any other UID, only the host can change ownership.
  for dir in "$DATA_DIR" "$ICONS_DIR"; do
    [ -d "$dir" ] || continue
    if [ "$uid" != 0 ]; then
      can_write "$dir" ||
        echo "stackyard: UID $uid cannot write $dir; config and icon writes will fail. Make it writable by $uid:$(id -g) on the host." >&2
      continue
    fi
    if su -s /bin/sh node -c "test -w \"$dir\"" 2>/dev/null; then continue; fi
    chown -R node:node "$dir" ||
      echo "stackyard: cannot take ownership of $dir; config and icon writes will fail" >&2
  done

  # Fail fast and loudly rather than starting with a config nginx will reject.
  # -q keeps the two success lines out of every boot; set -eu still stops here
  # on failure, and nginx still prints what it rejected.
  nginx -t -q -e stderr

  # supervisord always exits 0 on SIGTERM, including the SIGTERM that
  # scripts/exit-on-fatal.py sends when a program can no longer be started. The
  # marker carries that failure out as the container's exit code, so a dead API
  # reads as a failure rather than a normal shutdown and `restart: on-failure`
  # behaves the same as `unless-stopped` here.
  rm -f "$MARKER"

  # Run in the background rather than exec, so this script survives to read the
  # marker afterwards. That means signals no longer reach supervisord on their
  # own, and without forwarding a `docker stop` would kill this shell and leave
  # supervisord running until the kill timeout, with nothing shut down cleanly.
  #
  # supervisord stops with a traceback, before reading its config, when it
  # finds no writable temporary folder. The runtime folder is writable here and
  # only by this UID, unlike /tmp.
  TMPDIR="$RUNTIME_DIR" SUPERVISOR_FATAL_MARKER="$MARKER" "$@" &
  child=$!
  trap 'kill -TERM "$child" 2>/dev/null' TERM INT

  # Keep `|| status=$?`. A trapped signal makes `wait` return 143, and set -e
  # would exit here: the kernel then kills supervisord mid-shutdown.
  status=0
  wait "$child" || status=$?
  while kill -0 "$child" 2>/dev/null; do
    status=0
    wait "$child" || status=$?
  done

  if [ -f "$MARKER" ]; then
    echo "stackyard: $(cat "$MARKER") could not be started; exiting so the container is restarted" >&2
    rm -f "$MARKER"
    exit 1
  fi

  exit "$status"
}
